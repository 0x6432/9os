ROOT = Path(__file__).resolve().parents[1]
def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result
C = module('extracted_check', ROOT/'scripts/disk-root-extracted-check.py')
# Fixed independent fixture, not generated by the code under test.
ARCHIVE = base64.b64decode('MDcwNzAxMDAwMDAwMDEwMDAwNDFlZDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMjAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAyMDAwMDAwMDAuADA3MDcwMTAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDEwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwYjAwMDAwMDAwVFJBSUxFUiEhIQAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=')
CONFIG = b'timeout: 0\nverbose: no\n\n/9os\n    protocol: limine\n    path: boot():/boot/kernel.elf\n    module_path: boot():/boot/initramfs.cpio\n    module_string: initramfs\n    cmdline: root=/dev/vda1 root_required=1\n'

class ExtractedTree(unittest.TestCase):
    def tree(self, root):
        tree = Path(root)/'extract'; tree.mkdir(mode=0o700); (tree/'boot/limine').mkdir(parents=True)
        (tree/'boot/initramfs.cpio').write_bytes(ARCHIVE)
        (tree/'boot/limine/limine.conf').write_bytes(CONFIG)
        return tree
    def test_correct_tree(self):
        with tempfile.TemporaryDirectory() as d:
            t=self.tree(d); C.check(t); C.check(os.fsencode(t))
    def test_config_mutations(self):
        for mutation in (CONFIG+b'    cmdline: init=/bin/sh\n', CONFIG+b'ignored=yes\n', CONFIG.replace(b'root=/dev/vda1', b'root=/dev/vdb1'), CONFIG[:-1]):
            with self.subTest(mutation=mutation), tempfile.TemporaryDirectory() as d:
                t=self.tree(d); f=t/'boot/limine/limine.conf'; f.write_bytes(mutation)
                with self.assertRaises(ValueError): C.check(t)
    def test_archive_mutations_and_newer_stale_bytes(self):
        for change in (b'', b'not an archive', ARCHIVE[:-1]+b'x', ARCHIVE+b'x'):
            with self.subTest(length=len(change)), tempfile.TemporaryDirectory() as d:
                t=self.tree(d); f=t/'boot/initramfs.cpio'; f.write_bytes(change)
                os.utime(f, (2000000000, 2000000000))
                with self.assertRaises(ValueError): C.check(t)
    def test_links_and_missing(self):
        for scenario in ('root_link', 'root_link_slash', 'boot_link', 'config_link', 'archive_hardlink', 'missing'):
            with self.subTest(scenario=scenario), tempfile.TemporaryDirectory() as d:
                t=self.tree(d)
                if scenario in ('root_link', 'root_link_slash'):
                    link=Path(d)/'alias'; link.symlink_to(t, target_is_directory=True); t=str(link)+'/' if scenario == 'root_link_slash' else link
                elif scenario == 'boot_link':
                    (t/'boot').rename(t/'realboot'); (t/'boot').symlink_to('realboot', target_is_directory=True)
                elif scenario == 'config_link':
                    f=t/'boot/limine/limine.conf'; f.rename(t/'config'); f.symlink_to('../../config')
                elif scenario == 'archive_hardlink': os.link(t/'boot/initramfs.cpio', Path(d)/'hardlink')
                else: (t/'boot/initramfs.cpio').unlink()
                with self.assertRaises((ValueError, OSError)): C.check(t)
    def test_permissions_refused(self):
        for path in ('', 'boot', 'boot/limine', 'boot/limine/limine.conf', 'boot/initramfs.cpio'):
            for bit in ((0o040, 0o010, 0o020, 0o002) if not path else (0o020, 0o002)):
                with self.subTest(path=path, bit=bit), tempfile.TemporaryDirectory() as d:
                    t=self.tree(d); f=t/path; f.chmod(f.stat().st_mode | bit)
                    with self.assertRaises(ValueError): C.check(t)

    def test_wrong_ownership_refused(self):
        actual = os.fstat
        for kind in ('directory', 'file'):
            with self.subTest(kind=kind), tempfile.TemporaryDirectory() as d:
                t=self.tree(d)
                def fake(fd):
                    st=actual(fd)
                    if (kind == 'directory' and stat.S_ISDIR(st.st_mode)) or (kind == 'file' and stat.S_ISREG(st.st_mode)):
                        return SimpleNamespace(st_mode=st.st_mode, st_uid=os.geteuid()+1, st_nlink=st.st_nlink, st_size=st.st_size, st_dev=st.st_dev, st_ino=st.st_ino, st_mtime_ns=st.st_mtime_ns, st_ctime_ns=st.st_ctime_ns)
                    return st
                with mock.patch.object(C.os, 'fstat', side_effect=fake):
                    with self.assertRaises(ValueError): C.check(t)

    def test_fifo_does_not_block(self):
        with tempfile.TemporaryDirectory() as d:
            t=self.tree(d); f=t/'boot/initramfs.cpio'; f.unlink(); os.mkfifo(f)
            result=subprocess.run([sys.executable, str(ROOT/'scripts/disk-root-extracted-check.py'), str(t)],
                                  capture_output=True, timeout=3)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn(b'extracted path is not a regular file', result.stderr)

if __name__ == '__main__': unittest.main()
